// Generates THIRD_PARTY_NOTICES.md: every production dependency that ships in
// the desktop app, with its license and license text (U2-P6-20).
//
//   npm run notices           writes THIRD_PARTY_NOTICES.md
//   npm run notices -- --check  fails if the committed file is out of date
//
// npm: the production tree (`npm ls --omit=dev --all`), read from node_modules.
// Rust: `cargo metadata --locked` for the two shipped targets (macOS Apple
// Silicon, Windows x64), read from the local crate sources. Run `npm ci` and
// `cargo fetch --locked --target x86_64-pc-windows-msvc` first.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "THIRD_PARTY_NOTICES.md");
const check = process.argv.includes("--check");

const licenseFile = (dir) =>
  readdirSync(dir)
    .filter((name) =>
      /^(licen[sc]e|copying|notice|unlicense)([-._].*)?$/i.test(name),
    )
    .filter((name) => !/\.(js|ts|json|rs)$/i.test(name))
    .sort();

const entries = new Map(); // "name@version" -> { name, version, license, source, texts }

function add(name, version, license, source, dir) {
  const key = `${name}@${version}`;
  if (entries.has(key)) return;
  const texts = [];
  for (const file of licenseFile(dir)) {
    try {
      const text = readFileSync(join(dir, file), "utf8")
        .replace(/\r\n/g, "\n")
        .trim();
      if (text) texts.push(text);
    } catch {
      // A directory with a license-like name is skipped.
    }
  }
  entries.set(key, {
    name,
    version,
    license: license || "UNKNOWN",
    source,
    texts,
  });
}

// npm production packages.
const tree = JSON.parse(
  execFileSync("npm", ["ls", "--omit=dev", "--all", "--json"], {
    cwd: root,
    maxBuffer: 1 << 28,
  }).toString(),
);
(function walk(deps) {
  for (const [name, node] of Object.entries(deps ?? {})) {
    const dir = join(root, "node_modules", name);
    if (existsSync(join(dir, "package.json"))) {
      const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
      const license =
        typeof pkg.license === "string"
          ? pkg.license
          : JSON.stringify(pkg.license ?? pkg.licenses);
      add(name, pkg.version, license, "npm", dir);
    }
    walk(node.dependencies);
  }
})(tree.dependencies);

// Rust crates for both shipped platforms.
for (const target of ["aarch64-apple-darwin", "x86_64-pc-windows-msvc"]) {
  const meta = JSON.parse(
    execFileSync(
      "cargo",
      [
        "metadata",
        "--locked",
        "--format-version",
        "1",
        "--filter-platform",
        target,
        "--manifest-path",
        join(root, "src-tauri/Cargo.toml"),
      ],
      { maxBuffer: 1 << 28 },
    ).toString(),
  );
  const own = new Set(meta.workspace_members);
  for (const pkg of meta.packages) {
    if (own.has(pkg.id)) continue;
    add(
      pkg.name,
      pkg.version,
      pkg.license,
      "crates.io",
      dirname(pkg.manifest_path),
    );
  }
}

const sorted = [...entries.values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
);
const hash = (text) =>
  createHash("sha256").update(text).digest("hex").slice(0, 12);

// Group identical license texts so each appears once.
const groups = new Map();
for (const entry of sorted) {
  for (const text of entry.texts) {
    const id = hash(text);
    if (!groups.has(id)) groups.set(id, { text, packages: [] });
    groups.get(id).packages.push(`${entry.name} ${entry.version}`);
  }
}
const noText = sorted.filter((entry) => entry.texts.length === 0);

const lines = [
  "# Third-party notices",
  "",
  "Unhollowed 2 includes the open-source packages below. Each remains under its own license. This file is generated by `npm run notices` from the dependency lockfiles; do not edit it by hand.",
  "",
  `${sorted.length} packages (${sorted.filter((e) => e.source === "npm").length} npm, ${sorted.filter((e) => e.source === "crates.io").length} Rust crates), for macOS Apple Silicon and Windows x64.`,
  "",
  "## Packages",
  "",
  "| Package | Version | License | Source |",
  "| --- | --- | --- | --- |",
  ...sorted.map(
    (e) =>
      `| ${e.name} | ${e.version} | ${e.license.replace(/\|/g, "/")} | ${e.source} |`,
  ),
  "",
  "## License texts",
  "",
  "Packages that ship identical license text share one entry.",
  "",
];
for (const [id, group] of [...groups.entries()].sort((a, b) =>
  a[1].packages[0].localeCompare(b[1].packages[0]),
)) {
  lines.push(
    `### ${group.packages.length === 1 ? group.packages[0] : `${group.packages[0]} and ${group.packages.length - 1} more`} (text ${id})`,
    "",
  );
  lines.push(
    `Applies to: ${group.packages.join(", ")}`,
    "",
    "```text",
    group.text,
    "```",
    "",
  );
}
if (noText.length) {
  lines.push(
    "## Packages with no license file in their source",
    "",
    "These declare a license in their metadata but ship no license file. The declared license applies; add the text from the project's repository if the license requires it to accompany distributions.",
    "",
    ...noText.map((e) => `- ${e.name} ${e.version}: ${e.license}`),
    "",
  );
}
const content = lines.join("\n");

if (check) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== content) {
    console.error(
      "THIRD_PARTY_NOTICES.md is out of date. Run `npm run notices`.",
    );
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is up to date.");
} else {
  writeFileSync(out, content);
  console.log(
    `Wrote ${sorted.length} packages and ${groups.size} license texts (${noText.length} without a license file).`,
  );
}
